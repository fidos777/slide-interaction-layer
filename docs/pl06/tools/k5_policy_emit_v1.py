BANNER = ("<!-- GENERATED by docs/pl06/tools/k5_policy_emit_v1.py — "
          f"Stage {P.STAGE}. Edit the model, not this file. -->")


def _w(name, text):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
        f.write(text)
    return name


def _j(name, obj):
    return _w(name, json.dumps(obj, ensure_ascii=False, indent=1) + "\n")


def _tbl(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ")
                                     for c in r) + " |")
    return "\n".join(out)


def _ingestion_md(r):
    L = [BANNER, "", "# K5 Kelompok 0 v1.2 — Bariah decision ingestion", "", "```",
         f"DOCUMENT   = {r['source_document']['filename']}",
         f"SHA256     = {r['source_document']['sha256']}",
         f"BYTES      = {r['source_document']['bytes']:,}",
         f"REVIEWER   = {r['reviewer']['name']} ({r['reviewer']['role']})",
         f"VERDICT    = {r['overall_verdict']['ticked']}",
         f"DECISIONS  = {r['modelled_total']} of {r['declared_total']} declared",
         f"APPROVED   = {len(r['approved_ids'])}",
         f"PENDING    = {len(r['pending_ids'])}  {r['pending_ids']}", "```", "",
         "## Provenance", "", r["reviewer"]["provenance_note"], "",
         _tbl(["field", "value"],
              [["name", r["reviewer"]["name"]], ["role", r["reviewer"]["role"]],
               ["course", r["reviewer"]["course"]],
               ["scope", r["reviewer"]["document_scope"]],
               ["version", r["reviewer"]["document_version"]],
               ["date in closing block", r["reviewer"]["date_in_closing_block"]],
               ["header-table review date",
                r["reviewer"]["review_date_field_in_header_table"]],
               ["signature line", r["reviewer"]["signature_line"]],
               ["tracked changes", r["source_document"]["tracked_changes"]],
               ["Word comments", r["source_document"]["word_comments"]]]), "",
         r["source_document"]["tracked_changes_basis"], "",
         "## Bariah's closing note, verbatim", "",
         "> " + r["overall_verdict"]["closing_note_verbatim"], "",
         "## Deadlines stated in the document", "",
         _tbl(["item", "value"],
              [["Bariah feedback required before",
                r["deadlines"]["bariah_feedback_required_before"]],
               ["internal K5 storyboard target",
                r["deadlines"]["internal_k5_storyboard_target"]]]), "",
         r["deadlines"]["caveat_verbatim"], "",
         "## The seventeen decisions", "",
         _tbl(["id", "title", "checkbox", "status", "scope", "prose overrides tick"],
              [[d["id"], d["title"], d.get("checkbox") or "— none ticked —",
                d["status"], d.get("scope") or "—",
                "**YES**" if d.get("prose_overrides_checkbox") else "no"]
               for d in r["decisions"]]), ""]
    L += ["## Effective rules, and Bariah's own words", ""]
    for d in r["decisions"]:
        L += [f"### {d['id']} — {d['title']}", ""]
        if d.get("checkbox"):
            L.append(f"Ticked: **{d['checkbox']}**")
        else:
            L.append("Ticked: **nothing** — no option selected")
        L.append("")
        if d.get("bariah_prose"):
            L += ["Bariah's amendment, verbatim:", ""]
            L += ["> " + ln for ln in d["bariah_prose"].split("\n")]
            L.append("")
        else:
            L += ["Bariah's amendment field: *blank*", ""]
        if d.get("effective_rule"):
            L += [f"**Effective rule.** {d['effective_rule']}", ""]
        else:
            L += ["**No effective rule** — this decision is pending.", ""]
        for k in ("override_note", "note_for_summaries", "cross_course_note",
                  "worked_example", "tick_note", "unblocked_by"):
            if d.get(k):
                L += [f"*{k.replace('_', ' ')}:* {d[k]}", ""]
    L += ["## CAIR sub-points Bariah did not answer", "",
          "Silence is not approval. These stay CAIR proposals.", "",
          _tbl(["decision", "sub-point", "status"],
               [[s["decision"], s["subpoint"], s["status"]]
                for s in r["unresolved_subpoints"]]), "",
          "## Section B", "", r["section_b_note"], ""]
    return "\n".join(L)


def _matrix_md(m):
    return "\n".join([
        BANNER, "", "# K5 decision-impact matrix", "",
        f"{m['total']} rulings. {len(m['affected_by_section_b'])} are themselves Section B "
        f"and remain undecided: {', '.join(m['affected_by_section_b'])}.", "",
        "No approved ruling in Sections A, C or D depends on Section B — Section B governs "
        "the review package and schedule, not the pattern policy. That is why storyboard "
        "modelling can continue while B is open.", "",
        _tbl(["ruling", "affected rule or generator", "affected units", "scope",
              "implementation status", "Section B affects it"],
             [[f"**{r['decision']}** {r['title']}", r["affected_rule_or_generator"],
               r["affected_units"], r["scope"] or "—", r["implementation_status"],
               "**yes**" if r["section_b_affects_it"] else "no"]
              for r in m["rows"]]), "",
        "## Notes", "",
        "\n".join(f"- **{r['decision']}** — {r['note']}" for r in m["rows"] if r["note"]),
        ""])


