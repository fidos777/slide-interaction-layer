def _forecast_md(f):
    L = [BANNER, "", "# K5 completion forecast", "", "```",
         f"STATUS = {f['status']}", "```", "", f["status_note"], "", f["basis"], "",
         "## Section B is resolved", "",
         _tbl(["field", "value"],
              [["decision date", f["section_b_resolved"]["date"]],
               ["deadline", f["section_b_resolved"]["deadline"]],
               ["met deadline", f["section_b_resolved"]["met_deadline"]],
               ["status", f["section_b_resolved"]["status"]]]), "",
         "Unblocked: " + "; ".join(f["section_b_resolved"]["what_it_unblocked"]) + ".", "",
         "Still not unblocked: "
         + "; ".join(f["section_b_resolved"]["what_it_did_not_unblock"]) + ".", "",
         "## The real review constraint", "",
         _tbl(["field", "value"],
              [[k.replace("_", " "), v] for k, v in f["review_constraint"].items()
               if k != "note"]), "",
         f["review_constraint"]["note"], "",
         "## What is still open", "",
         _tbl(["variable", "state"],
              [["slots per available day", f["open_variables"][
                  "slots_per_available_day"]],
               ["available dates", f["open_variables"]["available_dates"]],
               ["B2 density outcome", f["open_variables"]["b2_density_outcome"]]]), "",
         f["open_variables"]["consequence"], "",
         "## Fixed inputs", "",
         _tbl(["input", "value"], [[k.replace("_", " "), v]
                                   for k, v in f["fixed_inputs"].items()]), "",
         "## Conditional assumptions", ""]
    L += [f"- **{a.split(' — ')[0]}** — {a.split(' — ', 1)[1]}"
          if " — " in a else f"- {a}" for a in f["assumptions"]]
    L += ["", "## Scenarios at a glance", "",
          _tbl(["", "scenario", "slots/day (conditional)", "9 Aug target", "confidence"],
               [[s["id"], s["name"], s["slots_per_day_assumed"], s["target_9_aug"],
                 s["confidence"]] for s in f["scenarios"]]), ""]
    for s in f["scenarios"]:
        L += [f"## Scenario {s['id']} — {s['name']}", "",
              _tbl(["stage", "range"],
                   [["Section B decision date", s["section_b_decision_date"]],
                    ["slots per day (conditional)", s["slots_per_day_assumed"]],
                    ["calibration completion", s["calibration_completion_range"]],
                    ["batch generation start", s["batch_generation_start_range"]],
                    ["engineering generation completion",
                     s["engineering_generation_completion_range"]],
                    ["Bariah review / freeze completion",
                     s["bariah_review_freeze_completion_range"]],
                    ["full-K5 package completion",
                     s["full_k5_package_completion_range"]]]), "",
              "**Assumptions:** " + ", ".join(s["assumptions"]) + ".", "",
              "**Principal blockers:**", ""]
        L += [f"- {b}" for b in s["principal_blockers"]]
        if s.get("mitigation"):
            L += ["", f"**Mitigation.** {s['mitigation']}"]
        L += [""]
    L += ["## Deliberately not forecast", ""]
    L += [f"- {x}" for x in f["what_is_not_forecast"]]
    L += [""]
    return "\n".join(L)


def _qa_md(s):
    return "\n".join([
        BANNER, "", "# K5 Bariah-policy QA report", "", "```",
        f"SUITE_ID = {s['suite_id']}",
        f"GATES    = {s['total']}",
        f"PASSED   = {s['passed']}",
        f"FAILED   = {len(s['failed'])}",
        f"ORACLE_SEPARATION_STRUCTURAL = {s['oracle_separation_structural']}", "```", "",
        "Own identity and own total. No sibling suite is merged in or edited.", "",
        _tbl(["area", "gates"], [[k, v] for k, v in s["by_type"].items() if v]), "",
        _tbl(["oracle basis", "gates"],
             [[k, v] for k, v in s["by_oracle_basis"].items()]), "",
        "## Every gate", "",
        _tbl(["gate", "area", "basis", "population", "ok"],
             [[g["gate_id"], g["gate_type"], g["oracle_basis"], g["population"],
               "yes" if g["ok"] else "**NO**"] for g in s["gates"]]), "",
        "## Not checked", "",
        "\n".join(f"- {n}" for n in s["not_checked"]), ""])


def _mut_md(r):
    return "\n".join([
        BANNER, "", "# K5 Bariah-policy mutation report", "", "```",
        f"SUITE_ID = {r['suite_id']}",
        f"FIXTURES = {r['fixture_count']}",
        f"DETECTED = {r['detected']}",
        f"MISSED   = {len(r['missed'])}",
        f"BASELINE = {r['baseline_pass']}/{r['baseline_total']}", "```", "",
        _tbl(["fixture", "what it breaks", "target", "gates that fired"],
             [[f["fixture_id"], f["title"], f["target"],
               ", ".join(f"`{g}`" for g in f["fired"]) or "**NONE — MISSED**"]
              for f in r["fixtures"]]), ""])


def emit_all():
    rec = P.ingestion_record()
    m = AP.impact_matrix()
    c = AP.calibration_units()
    s = AP.outside_pl06()
    qa = QA.summary()
    mu = MU.main()
    return [
        _j("K5_BARIAH_DECISION_INGESTION_v1.json", rec),
        _w("K5_BARIAH_DECISION_INGESTION_v1.md", _ingestion_md(rec)),
        _j("K5_DECISION_IMPACT_MATRIX_v1.json", m),
        _w("K5_DECISION_IMPACT_MATRIX_v1.md", _matrix_md(m)),
        _j("K5_CALIBRATION_REEVALUATION_v1.json", c),
        _w("K5_CALIBRATION_REEVALUATION_v1.md", _calibration_md(c)),
        _j("K5_STRUCTURES_OUTSIDE_PL06_v1.json", s),
        _w("K5_STRUCTURES_OUTSIDE_PL06_v1.md", _structures_md(s)),
        _j("K5_COMPLETION_FORECAST_v1.json", AP.FORECAST),
        _w("K5_COMPLETION_FORECAST_v1.md", _forecast_md(AP.FORECAST)),
        _j("K5_POLICY_QA_REPORT_v1.json", qa),
        _w("K5_POLICY_QA_REPORT_v1.md", _qa_md(qa)),
        _w("K5_POLICY_MUTATION_REPORT_v1.md", _mut_md(mu)),
    ]


if __name__ == "__main__":
    for n in emit_all():
        print("wrote", n)
