def emit_predicate_and_xml():
    audit = P.summary()
    proofs = X.proofs()
    a = _j("T04_PREDICATE_AND_XML_AUDIT_v1.json",
           dict(stage=S.STAGE, generated_by=S.GENERATED_BY,
                predicate_audit=audit, xml_proofs=proofs))

    p = [_hdr("T04 — FILTERED-POPULATION AND XML ELEMENT AUDIT",
              [f"CLOSED_POPULATIONS   = {audit['closed_populations']}",
               f"EXCLUDED_POPULATIONS = {audit['excluded_populations']}",
               f"FAILING              = {audit['failing'] or 'none'}",
               f"XML_PROOF_CASES      = {len(proofs)}"]),
         "# 1. Why this audit exists", "",
         "Fixture `C-05` got past the Stage 4.2F-B0.9 suite. A gate selected its population "
         "by a mutable property and then checked that property — so when the mutation made a "
         "record leave the population, the gate saw a smaller, still-correct population and "
         "passed. **A filter cannot observe its own departures.**", "",
         "Every gate whose population is selected by a mutable property now carries three "
         "assertions rather than one: the property check, a named-membership assertion, and a "
         "population-count delta.", "",
         "# 2. Closed populations", "",
         _tbl(["ID", "Selector", "Mutable property", "Expected", "Observed", "+", "−",
               "Guarded by"],
              [(r["population_id"], f"`{r['selector']}`", r["mutable_property"],
                r["expected_count"], r["observed_count"],
                len(r["unexpected_additions"]), len(r["unexpected_removals"]),
                ", ".join(r["guarded_by"])) for r in audit["rows"]]), "",
         "Named members, in full:", ""]
    for r in audit["rows"]:
        p += [f"- **{r['population_id']}** `{r['selector']}` → "
              + ", ".join(r["observed_members"])
              + (f"  (origin fixture {r['origin_fixture']})")]

    p += ["", "# 3. Documented exclusions", "",
          "Naming members is only meaningful for a population whose membership is itself a "
          "governed fact. For open-ended populations a named list would have to be edited on "
          "every unrelated change, which trains the reader to ignore it. These five are "
          "excluded on purpose, each with the delta guard that covers it instead.", "",
          _tbl(["ID", "Selector", "Used by", "Why excluded", "Delta guard"],
               [(x["exclusion_id"], x["selector"], ", ".join(x["used_by"]), x["why"],
                 x["delta_guard"]) for x in audit["exclusions"]]), "",
          "# 4. XML element identity", "",
          "Substring matching on OOXML is wrong in a way that reads as right. `<w:insideH>` "
          "starts with `<w:ins`; `<w:tcPr>` starts with `<w:t`. The first of those nearly "
          "produced a false claim that the authority document contained twelve tracked "
          "insertions. Element checks now match namespace plus local name exactly.", "",
          _tbl(["Case", "Kind", "What it proves", "Exact match", "Naive substring",
                "Naive would have been wrong"],
               [(c["case_id"], c["kind"], c["description"], c["exact_match_count"],
                 c["naive_substring_count"],
                 "yes" if c["naive_would_have_been_wrong"] else "n/a — positive control")
                for c in proofs]), "",
          "`XML-04` is a positive control: it exists so the helper cannot pass by returning "
          "zero for everything.", ""]
    return [a, _w("T04_PREDICATE_AND_XML_AUDIT_v1.md", "\n".join(p))]


