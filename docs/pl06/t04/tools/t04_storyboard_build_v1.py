def render_previews():
    from PIL import Image, ImageDraw, ImageFont

    def font(sz, bold=False):
        base = "/usr/share/fonts/truetype/liberation/"
        name = "LiberationSans-Bold.ttf" if bold else "LiberationSans-Regular.ttf"
        try:
            return ImageFont.truetype(base + name, sz)
        except Exception:
            return ImageFont.load_default()

    W, H = 1280, 720
    outdir = os.path.join(OUT, "storyboard_preview")
    os.makedirs(outdir, exist_ok=True)
    # Clear first. A previous run's pages survive a re-render otherwise, and a reviewer
    # opening the folder cannot tell a stale page from a current one — the first pass here
    # left four orphans behind when pagination changed the filenames.
    for f in os.listdir(outdir):
        if f.endswith(".png"):
            os.remove(os.path.join(outdir, f))
    made = []
    rgb = {k: tuple(int(str(v)[i:i + 2], 16) for i in (0, 2, 4))
           for k, v in PROV_COLOUR.items()}

    for sl in M.slides():
        sc = sl["screen"]
        img = Image.new("RGB", (W, H), (255, 255, 255))
        d = ImageDraw.Draw(img)
        d.text((48, 34), f"{sc['screen_id']}  ·  {sc['treatment']}", font=font(15, True),
               fill=(107, 107, 107))
        d.text((48, 58), sc["title_ms"] + sl["title_suffix"], font=font(28, True),
               fill=(26, 26, 26))
        d.line([(48, 108), (W - 48, 108)], fill=(216, 216, 216), width=2)

        y = 130
        d.text((48, y), "KANDUNGAN SKRIN" + (" (sambungan)" if sl["is_continuation"]
                                             else ""),
               font=font(12, True), fill=(107, 107, 107))
        y += 24
        overflowed = False
        for b in sl["blocks"]:
            colour = rgb[b["provenance"]]
            tag = PROV_TAG[b["provenance"]]
            txt = f"{tag} · {b['text']}"
            f = font(14 if b["provenance"] != "CAIR_STRUCTURAL" else 12)
            # naive wrap at the column width
            words, line = txt.split(), ""
            for w in words:
                probe = (line + " " + w).strip()
                if d.textlength(probe, font=f) > 700:
                    d.text((48 + 14 * b.get("list_level", 0), y), line, font=f, fill=colour)
                    y += 20
                    line = w
                else:
                    line = probe
            if line:
                d.text((48 + 14 * b.get("list_level", 0), y), line, font=f, fill=colour)
                y += 22
            if y > H - 90:
                # Should be unreachable: pagination exists so nothing is ever cut off. If it
                # fires, the preview says so loudly rather than quietly eliding content.
                overflowed = True
                d.text((48, y), "TRUNCATED — PAGINATION FAILED", font=font(13, True),
                       fill=(183, 28, 28))
                break

        rx, ry = 810, 130
        d.text((rx, ry), "INTERAKSI", font=font(12, True), fill=(107, 107, 107))
        ry += 22
        for st in sc["interaction_states"]:
            d.text((rx, ry), f"· {st}", font=font(12), fill=(26, 26, 26))
            ry += 18
        v = sc["visual"]
        ry += 12
        d.text((rx, ry), "VISUAL", font=font(12, True), fill=(107, 107, 107))
        ry += 22
        if v["asset_group_ids"]:
            d.text((rx, ry), " · ".join(v["asset_group_ids"]), font=font(13, True),
                   fill=(26, 26, 26))
            ry += 20
            if v["do_not_reuse_obligations"]:
                d.text((rx, ry), "TIDAK BOLEH DIKONGSI", font=font(11, True),
                       fill=(183, 28, 28))
                ry += 18
            d.text((rx, ry), "ASET BELUM DIHASILKAN", font=font(11, True),
                   fill=(183, 28, 28))
        else:
            d.text((rx, ry), "Tiada visual khusus", font=font(12), fill=(107, 107, 107))

        d.line([(48, H - 60), (W - 48, H - 60)], fill=(216, 216, 216), width=1)
        d.text((48, H - 48),
               f"{M.LEARNER_DISPLAY_UNIT} · skrin {sc['position']} daripada "
               f"{M.SCREEN_COUNT_EXPECTED}"
               + ("" if sl["page_count"] == 1
                  else f"  ·  halaman {sl['page_index']}/{sl['page_count']}"),
               font=font(11), fill=(107, 107, 107))

        suffix = "" if sl["page_count"] == 1 else f"_p{sl['page_index']}"
        p = os.path.join(outdir, f"{sc['screen_id']}{suffix}.png")
        img.save(p)
        made.append(dict(path=p, screen_id=sc["screen_id"], page=sl["page_index"],
                         overflowed=overflowed))
    return made


