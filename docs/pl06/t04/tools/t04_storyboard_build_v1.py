def _title_slide(prs):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    tf = _tf(slide, MARGIN, Emu(1600200), Emu(SLIDE_W - 2 * MARGIN), Emu(2400000))
    _p(tf, "STORYBOARD UNTUK SEMAKAN BARIAH", 16, MUTED, bold=True, first=True)
    _p(tf, f"{M.LEARNER_DISPLAY_UNIT}: {M.LEARNER_DISPLAY_UNIT_TITLE}", 34, INK, bold=True)
    _p(tf, f"{M.SCREEN_COUNT_EXPECTED} skrin pembelajaran", 18, MUTED)
    _p(tf, "", 10)
    _p(tf, f"Rujukan dalaman: {M.INTERNAL_UNIT_ID}", 11, MUTED, italic=True)
    _p(tf, "Storyboard sahaja. Aset visual MMD belum dihasilkan.", 11, PLACEHOLDER,
       italic=True)
    _p(tf, LEGEND, 10, MUTED, italic=True)
    return slide


def _screen_slide(prs, sl):
    sc = sl["screen"]
    slide = prs.slides.add_slide(prs.slide_layouts[6])

    # Header: screen id + title. The screen ID is production metadata, kept visually distinct
    # from the learner-facing title beside it.
    tf = _tf(slide, MARGIN, Emu(320000), Emu(SLIDE_W - 2 * MARGIN), Emu(700000))
    _p(tf, f"{sc['screen_id']}   ·   {sc['treatment']}", 11, MUTED, bold=True, first=True)
    _p(tf, sc["title_ms"] + sl["title_suffix"], 24, INK, bold=True)
    _rule(slide, Emu(1150000))

    # Learner content column.
    col_w = Emu(int((SLIDE_W - 2 * MARGIN) * 0.60))
    tf = _tf(slide, MARGIN, Emu(1320000), col_w, Emu(4600000))
    _p(tf, "KANDUNGAN SKRIN" + (" (sambungan)" if sl["is_continuation"] else ""),
       10, MUTED, bold=True, first=True)
    for b in sl["blocks"]:
        colour = PROV_COLOUR[b["provenance"]]
        tag = PROV_TAG[b["provenance"]]
        size = 11 if b["provenance"] == "CAIR_STRUCTURAL" else 13
        _p(tf, f"{tag} · {b['text']}", size, colour, indent=b.get("list_level") or 0)

    # Right column: interaction, visual, traceability.
    rx = Emu(int(MARGIN + col_w + 300000))
    rw = Emu(int(SLIDE_W - MARGIN - rx))
    tf = _tf(slide, rx, Emu(1320000), rw, Emu(4600000))
    _p(tf, "INTERAKSI", 10, MUTED, bold=True, first=True)
    for st in sc["interaction_states"]:
        _p(tf, f"· {st}", 10, INK)
    if sc["named_reveal_items"]:
        _p(tf, "Item pendedahan:", 10, MUTED, bold=True)
        for r in sc["named_reveal_items"]:
            _p(tf, f"· {r}", 10, INK)

    v = sc["visual"]
    _p(tf, "", 8)
    _p(tf, "VISUAL", 10, MUTED, bold=True)
    if v["asset_group_ids"]:
        _p(tf, "· ".join(v["asset_group_ids"]), 11, INK, bold=True)
        for lbl in v["asset_group_labels"]:
            _p(tf, lbl, 10, INK)
        _p(tf, f"Dasar guna semula: {v['reuse_policy']}", 9, MUTED)
        if v["do_not_reuse_obligations"]:
            _p(tf, "TIDAK BOLEH DIKONGSI: " + ", ".join(v["do_not_reuse_obligations"]),
               9, PLACEHOLDER, bold=True)
        _p(tf, "ASET BELUM DIHASILKAN", 10, PLACEHOLDER, bold=True)
    else:
        _p(tf, "Tiada visual khusus", 10, MUTED, italic=True)

    _p(tf, "", 8)
    _p(tf, "SUMBER DAN KEPUTUSAN", 10, MUTED, bold=True)
    _p(tf, ("Baris modul: " + ", ".join(sc["source_row_ids"])) if sc["source_row_ids"]
       else "Skrin struktur — tiada baris modul", 8, MUTED)
    _p(tf, "Keputusan: " + ", ".join(sc["decision_ids"]), 8, MUTED)

    # Footer.
    tf = _tf(slide, MARGIN, Emu(6150000), Emu(SLIDE_W - 2 * MARGIN), Emu(500000))
    _p(tf, f"{M.LEARNER_DISPLAY_UNIT} · skrin {sc['position']} daripada "
           f"{M.SCREEN_COUNT_EXPECTED}", 9, MUTED, first=True)
    # The per-screen authority note stays in the registers and off the slide. It is English
    # production prose, and on two screens it quoted the retired label "Tamat Bahagian" onto
    # a deck whose whole point is that T04 has no Bahagian.
    return slide


def build_pptx():
    prs = Presentation()
    prs.slide_width = SLIDE_W
    prs.slide_height = SLIDE_H
    _title_slide(prs)
    for sl in M.slides():
        _screen_slide(prs, sl)
    os.makedirs(M.PPTX_DIR, exist_ok=True)
    path = os.path.join(M.PPTX_DIR, M.PPTX_NAME)
    prs.save(path)
    return path


