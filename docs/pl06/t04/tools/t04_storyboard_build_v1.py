def _tf(slide, x, y, w, h, wrap=True):
    box = slide.shapes.add_textbox(x, y, w, h)
    tf = box.text_frame
    tf.word_wrap = wrap
    tf.margin_left = tf.margin_right = Emu(0)
    tf.margin_top = tf.margin_bottom = Emu(0)
    return tf


def _p(tf, text, size=14, colour=INK, bold=False, italic=False, first=False, indent=0,
       align=PP_ALIGN.LEFT):
    para = tf.paragraphs[0] if first else tf.add_paragraph()
    para.alignment = align
    para.level = min(int(indent or 0), 4)
    run = para.add_run()
    run.text = text
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    run.font.color.rgb = colour
    run.font.name = "Arial"
    return para


def _rule(slide, y):
    from pptx.enum.shapes import MSO_SHAPE
    ln = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, MARGIN, y,
                                Emu(SLIDE_W - 2 * MARGIN), Emu(9525))
    ln.fill.solid()
    ln.fill.fore_color.rgb = RULE
    ln.line.fill.background()
    ln.shadow.inherit = False
    return ln


