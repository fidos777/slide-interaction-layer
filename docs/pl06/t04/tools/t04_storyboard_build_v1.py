"""Stage 4.2F-B1 — build the T04 review PPTX and the registers, from the controlled model.

The deck is generated, never hand-edited. Every text frame on every slide is placed from
`t04_storyboard_model_v1`, so a sentence cannot appear in the PPTX without existing in the
model, and the QA suite re-reads the built file from disk rather than trusting this builder.

Two things this stage does NOT claim:

  * that the deck looks right in Microsoft PowerPoint — no Impress filter exists here, so no
    native render was performed and none is asserted;
  * that any visual exists — every visual slot is a labelled placeholder naming the asset
    group and obligations it stands for.
"""
