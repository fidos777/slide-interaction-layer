"""Stage 4.2F-B0.9 — emit every authority-ingestion artifact from one data source.

Every string in every emitted file is projected from t04_authority_data_v1. Nothing is typed
here that does not exist as a record there, so a claim cannot appear in a Markdown file
without also existing in the controlled model.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import t04_authority_data_v1 as D   # noqa: E402

OUT = os.path.abspath(os.path.join(HERE, ".."))
BANNER = (f"<!-- GENERATED by {D.GENERATED_BY} — Stage {D.STAGE}. "
          "Edit the data module, not this file. -->")


def _w(name, text):
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
        f.write(text if text.endswith("\n") else text + "\n")
    return name


def _j(name, obj):
    return _w(name, json.dumps(obj, ensure_ascii=False, indent=1))


def _hdr(title, extra=()):
    lines = [BANNER, "", f"# {title}", "", "```",
             f"STAGE                = {D.STAGE}",
             f"SUITE_ID             = {D.SUITE_ID}",
             f"INTERNAL_UNIT_ID     = {D.INTERNAL_UNIT_ID}",
             f"LEARNER_DISPLAY_UNIT = {D.LEARNER_DISPLAY_UNIT} — "
             f"{D.LEARNER_DISPLAY_UNIT_TITLE}",
             f"INSTRUCTIONAL_AUTHORITY = BARIAH_AHMAD"]
    lines += list(extra) + ["```", ""]
    return "\n".join(lines)


def _tbl(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ")
                                     for c in r) + " |")
    return "\n".join(out)


def _q(s):
    return f"“{s}”" if s else "—"


