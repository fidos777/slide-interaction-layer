def emit_evidence():
    obj = dict(
        stage=D.STAGE, suite_id=D.SUITE_ID, generated_by=D.GENERATED_BY,
        evidence_classes=D.EVIDENCE_CLASSES,
        evidence_dir=D.EVIDENCE_DIR,
        records=D.EVIDENCE,
        primary_artifact_mechanism=D.PRIMARY_ARTIFACT_MECHANISM,
        unit_label_ruling=D.UNIT_LABEL_RULING)
    a = _j("T04_AUTHORITY_EVIDENCE_REGISTER_v1.json", obj)

    p = [_hdr("T04 — AUTHORITY EVIDENCE REGISTER",
              [f"EVIDENCE_RECORDS     = {len(D.EVIDENCE)}",
               f"PRIMARY_SHA256       = {D.PRIMARY_DOCX_SHA256}",
               f"PRIMARY_BYTES        = {D.PRIMARY_DOCX_BYTES}"]),
         "The hierarchy runs top to bottom. Anything lower may only restate what something "
         "higher decided.", ""]

    p.append(_tbl(["Level", "Evidence", "ID", "Supplied to this run", "SHA-256"],
                  [(r["evidence_class"], r["filename"], r["evidence_id"],
                    "yes" if r["supplied_in_this_run"] else "**NO**",
                    r["sha256"]) for r in D.EVIDENCE]))
    p.append("")

    for r in D.EVIDENCE:
        p += [f"## {r['evidence_id']} — {r['evidence_class']}", "",
              _tbl(["Field", "Value"], [
                  ("filename", r["filename"]),
                  ("frozen path", r["frozen_path"] or "—"),
                  ("supplied in this run", "yes" if r["supplied_in_this_run"] else "NO"),
                  ("byte size", r["byte_size"]),
                  ("SHA-256", r["sha256"]),
                  ("extent", r["dimensions_or_extent"]),
                  ("authority", r["authority"]),
                  ("authored with", r["authored_with"]),
                  ("date recorded", r["date_authority_recorded"]),
                  ("scope", r["scope"]),
              ]), "",
              f"**Authority wording.** {_q(r['authority_quote'])}", "",
              f"**Interpretation.** {r['interpretation']}", "",
              f"**Limitations.** {r['limitations']}", "",
              f"**Provenance.** {r['provenance_chain']}", ""]

    m = D.PRIMARY_ARTIFACT_MECHANISM
    p += ["## How the authority recorded her decisions", "",
          _tbl(["Check", "Observed"], [
              ("tracked changes present", str(m["tracked_changes_present"])),
              ("tracked change elements", str(m["tracked_change_element_count"])),
              ("Word comments present", str(m["word_comments_present"])),
              ("Word comments", str(m["word_comment_count"])),
              ("comments part in package", str(m["comments_part_present"])),
              ("decision mechanism", m["decision_mechanism"]),
          ]), "",
          m["note"], "",
          f"*Counting note.* {m['counting_trap']}", "",
          "## Unit labelling ruling", "",
          _tbl(["Field", "Value"], [
              ("ruling", D.UNIT_LABEL_RULING["ruling_id"]),
              ("internal unit ID", D.UNIT_LABEL_RULING["internal_unit_id"]),
              ("learner display unit", D.UNIT_LABEL_RULING["learner_display_unit"]),
              ("scope", D.UNIT_LABEL_RULING["scope"]),
          ]), "",
          f"**Authority wording.** {_q(D.UNIT_LABEL_RULING['authority_quote'])}", "",
          D.UNIT_LABEL_RULING["interpretation"], ""]

    b = _w("T04_AUTHORITY_EVIDENCE_REGISTER_v1.md", "\n".join(p))
    return [a, b]


